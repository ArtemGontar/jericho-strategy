export const ICON_NAMES = Object.keys(I);

export function iconParts(name: string): IconPart[] {
  return I[name] ?? I.hex;
}

const pathCache = new Map<string, Path2D>();
function path2d(d: string): Path2D {
  let p = pathCache.get(d);
  if (!p) {
    p = new Path2D(d);
    pathCache.set(d, p);
  }
  return p;
}

/** Draw an icon on a canvas, centred on (cx, cy), `size` pixels square. */
export function drawIcon(
  ctx: CanvasRenderingContext2D, name: string, cx: number, cy: number, size: number, color: string, fillColor: string = color, weight = 1.7,
): void {
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  const k = size / 24;
  ctx.scale(k, k);
  ctx.lineWidth = weight;
  ctx.lineJoin = 'round';
  ctx.lineCap = 'round';
  ctx.strokeStyle = color;
  ctx.fillStyle = fillColor;
  for (const [d, mode] of iconParts(name)) {
    const p = path2d(d);
    if (mode === 'f' || mode === 'b') {
      ctx.globalAlpha = mode === 'b' ? 0.28 : 1;
      ctx.fill(p);
      ctx.globalAlpha = 1;
    }
    if (mode === 's' || mode === 'b') ctx.stroke(p);
  }
  ctx.restore();
}

const SVG_NS = 'http://www.w3.org/2000/svg';

/** DOM icon. Colour follows `currentColor`, so CSS decides it. */
export function icon(name: string, size = 18, cls = ''): SVGSVGElement {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '1.7');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', `ico ${cls}`.trim());
  for (const [d, mode] of iconParts(name)) {
    const p = document.createElementNS(SVG_NS, 'path');
    p.setAttribute('d', d);
    if (mode === 'f') {
      p.setAttribute('fill', 'currentColor');
      p.setAttribute('stroke', 'none');
    } else if (mode === 'b') {
      p.setAttribute('fill', 'currentColor');
      p.setAttribute('fill-opacity', '0.28');
    }
    svg.appendChild(p);
  }
  return svg;
}

/** Icon key for a unit type, building id, resource or yield. */
export function iconFor(kind: 'unit' | 'building' | 'resource', id: string): string {
  if (kind === 'resource') return id;
  return id in I ? id : kind === 'unit' ? 'warrior' : 'wonder';
}
